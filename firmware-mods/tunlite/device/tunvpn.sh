#!/bin/sh
# tunvpn.sh - keeps the management OpenVPN tunnel of the Notion 5G up.
# Installed at /data/tunvpn/tunvpn.sh, run every minute by cron (/etc/crontabs/root):
#   * * * * * /data/tunvpn/tunvpn.sh check
# /etc/rc.d is read-only on this firmware, so cron is the boot hook and the watchdog at the same time.
# Settings live in uci (package tunvpn, edited from the web UI: Router > Advanced > Management VPN); the
# OpenVPN files in /data/tunvpn are generated from it on every start.
#
#   tunvpn.sh check    load tunlite.ko if needed, start openvpn if enabled and not running
#   tunvpn.sh restart  regenerate the config and restart openvpn
#   tunvpn.sh stop     stop openvpn (the module stays loaded)
#   tunvpn.sh status   one-line status
#   tunvpn.sh render   only regenerate client.conf / auth.txt
# CGI (lighttpd) and cron run with a reduced PATH: uci, iptables, tc, insmod live in /sbin and /usr/sbin
export PATH=/usr/sbin:/usr/bin:/sbin:/bin
D=/data/tunvpn
PIDF=/var/run/tunvpn.pid
TAG=tunvpn

cfg() { uci -q get "tunvpn.main.$1"; }
enabled() { [ "$(cfg enabled)" = 1 ]; }
running() { [ -f "$PIDF" ] && kill -0 "$(cat "$PIDF")" 2>/dev/null; }

render() {
	proto=$(cfg proto); [ "$proto" = udp ] || proto=tcp
	[ "$proto" = tcp ] && p=tcp-client || p=udp
	user=$(cfg username); pass=$(cfg password)
	{
		echo "# generated by tunvpn.sh from uci tunvpn - do not edit"
		echo "client"
		echo "dev tun0"
		echo "proto $p"
		echo "remote $(cfg remote) $(cfg port || echo 1194)"
		echo "connect-retry 5 60"
		echo "resolv-retry infinite"
		echo "nobind"
		[ -n "$user" ] && echo "auth-user-pass auth.txt"
		[ -s "$D/ca.crt" ] && echo "ca ca.crt"
		[ -s "$D/client.crt" ] && [ -s "$D/client.key" ] && { echo "cert client.crt"; echo "key client.key"; }
		c=$(cfg cipher); [ -n "$c" ] || c=AES-256-CBC
		echo "cipher $c"
		echo "data-ciphers $c:AES-256-GCM:AES-128-GCM"
		a=$(cfg auth); [ -n "$a" ] || a=SHA1
		echo "auth $a"
		if [ "$(cfg route_nopull)" != 0 ]; then
			echo "route-nopull"
			echo "pull-filter ignore redirect-gateway"
		fi
		echo "keepalive 10 60"
		echo "persist-tun"
		echo "persist-key"
		echo "verb 3"
	} > "$D/client.conf.tmp" && mv "$D/client.conf.tmp" "$D/client.conf"
	if [ -n "$user" ]; then
		( umask 077; printf '%s\n%s\n' "$user" "$pass" > "$D/auth.txt" )
	else
		rm -f "$D/auth.txt"
	fi
}

load_module() {
	grep -q '^tunlite ' /proc/modules && return 0
	insmod "$D/tunlite.ko" || { logger -t $TAG "insmod tunlite.ko failed"; return 1; }
	logger -t $TAG "tunlite loaded"
}

start() {
	load_module || return 1
	[ -c /dev/net/tun ] || { mkdir -p /dev/net; mknod /dev/net/tun c 10 200; }
	running && return 0
	[ -n "$(cfg remote)" ] || { logger -t $TAG "no server configured"; return 1; }
	render
	"$D/openvpn" --config "$D/client.conf" --cd "$D" --daemon tunvpn --writepid "$PIDF" \
		--log-append /tmp/tunvpn.log || { logger -t $TAG "openvpn failed to start"; return 1; }
	logger -t $TAG "openvpn started"
}

stop() {
	running && kill "$(cat "$PIDF")"
	for i in 1 2 3 4 5; do running || break; sleep 1; done
	rm -f "$PIDF"
}

case "$1" in
check)
	enabled || exit 0
	start
	[ -f /tmp/tunvpn.log ] && [ "$(wc -c < /tmp/tunvpn.log)" -gt 262144 ] && tail -c 65536 /tmp/tunvpn.log > /tmp/tunvpn.log.1 && mv /tmp/tunvpn.log.1 /tmp/tunvpn.log
	;;
restart) stop; enabled && start ;;
start) start ;;
stop) stop ;;
render) render ;;
status)
	m=no; grep -q '^tunlite ' /proc/modules && m=yes
	p=no; running && p="yes(pid $(cat "$PIDF"))"
	a=$(ip -4 -o addr show dev tun0 2>/dev/null | awk '{print $4}')
	echo "enabled=$(enabled && echo yes || echo no) module=$m openvpn=$p tun0=${a:-none}"
	;;
*) echo "usage: $0 check|restart|start|stop|status|render" >&2; exit 2 ;;
esac
